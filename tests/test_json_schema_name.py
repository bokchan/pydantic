def test_json_schema_name_generator_returns_none():
    """Test behavior when json_schema_name_generator returns None."""

    def conditional_namer(model: type) -> str | None:
        if model.__name__.startswith('Custom'):
            return f'Named{model.__name__}'
        return None

    class CustomModel(BaseModel):
        model_config = ConfigDict(json_schema_name_generator=conditional_namer)
        name: str

    class RegularModel(BaseModel):
        model_config = ConfigDict(json_schema_name_generator=conditional_namer)
        name: str

    _, combined_schema = models_json_schema(
        [
            (CustomModel, 'validation'),
            (RegularModel, 'validation'),
        ]
    )

    defs_keys = list(combined_schema['$defs'].keys())

    # CustomModel should have custom name
    assert any('NamedCustomModel' in key for key in defs_keys)

    # RegularModel should use default naming
    assert any('RegularModel' in key for key in defs_keys)


