def test_json_schema_name_with_model_title_generator():
    """Test interaction between json_schema_name and model_title_generator."""

    def title_gen(model: type) -> str:
        return f'Title: {model.__name__}'

    class Model(BaseModel):
        model_config = ConfigDict(json_schema_name='CustomDef', model_title_generator=title_gen)
        name: str

    class Container(BaseModel):
        model: Model

    schema = Container.model_json_schema()

    # Def name should use json_schema_name
    assert 'CustomDef' in schema['$defs']

    # Title should use model_title_generator
    assert schema['$defs']['CustomDef']['title'] == title_gen(Model)


def test_json_schema_name_custom_vs_default_collision():
    """Test that collision between custom name and default name raises an error."""

    # Model with custom name that collides with another model's default name
    class UserModel(BaseModel):
        model_config = ConfigDict(json_schema_name='DefaultNameModel')
        name: str

    # Model whose default name will collide with UserModel's custom name
    class DefaultNameModel(BaseModel):
        email: str

    # Should raise error about collision between custom and default names
    with pytest.raises(PydanticUserError, match='Custom JSON schema name "DefaultNameModel" collides'):
        models_json_schema(
            [
                (UserModel, 'validation'),
                (DefaultNameModel, 'validation'),
            ]
        )
